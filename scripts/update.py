"""One command to keep any raptor-generated repo current: update or migrate.

Run from the root of a repo generated by the raptor template (any version). This
entry point routes on the repo's type:

- Repo has ``.copier-answers.yml`` (copier-era): runs ``copier update --trust``
  with any extra arguments you pass through (e.g. ``--vcs-ref <ref>``).
- Repo has no ``.copier-answers.yml`` (cookiecutter-era): ``copier update``
  cannot help it (there is no answers file to update from), so this fetches
  ``scripts/migrate_to_copier.py`` from the template repository at its newest
  copier tag and runs that one-time migration. Afterwards ``copier update``
  works natively.

Nothing needs to be checked out locally: the migration script is fetched from
the remote template, and by default from its *newest copier tag*, so you always
run the latest version of it.

Usage (from the root of the repo to update)
-------------------------------------------
    uv run --python 3.11 <raptor>/scripts/update.py --check     # preview (cookiecutter repo)
    uv run --python 3.11 <raptor>/scripts/update.py --yes       # migrate  (cookiecutter repo)
    uv run --python 3.11 <raptor>/scripts/update.py --ref <ref> --check   # copier update --pretend (copier repo)
    uv run --python 3.11 <raptor>/scripts/update.py --ref <ref> --yes     # copier update --defaults (copier repo)

``--template`` selects the template URL/path; it defaults to the raptor repo.
``--ref`` picks the template ref (tag/branch) for both the migration script and
the target; the default is the template's newest copier tag. For a copier-era
repo the same flags map onto ``copier update``: ``--ref`` -> ``--vcs-ref``,
``--check`` -> ``--pretend --defaults``, ``--yes`` -> ``--defaults`` and
``-d key=value`` -> ``--data key=value``. Extra ``-d key=value`` pairs override
detected answers. For a copier-era repo, unrecognized arguments are passed
straight to ``copier update``.

Both routes warn when the branch being updated is behind the remote's default
branch (the PR back onto it would re-conflict); the migration additionally
refuses ``--yes`` until you rebase or pass ``--allow-behind``.

Requires git, and uv (to run the migration with python >= 3.11) or copier on
PATH for copier-era repos. Stdlib only otherwise.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

DEFAULT_TEMPLATE = "git@ssh.dev.azure.com:v3/GemeenteRotterdam/DAPR/raptor"
SCRIPT_NAME = "migrate_to_copier.py"


def git_env(*paths: Path | str) -> dict[str, str] | None:
    """Env trusting git to operate in the given dirs (CIFS/root-owned /tmp).

    ``GIT_TERMINAL_PROMPT=0`` makes git fail instead of hanging on a credential
    prompt we could never answer (our git output is captured, not a tty).
    """
    if not paths:
        env = os.environ.copy()
        env.setdefault("GIT_TERMINAL_PROMPT", "0")
        return env
    env = os.environ.copy()
    env.setdefault("GIT_TERMINAL_PROMPT", "0")
    base = int(env.get("GIT_CONFIG_COUNT", "0"))
    names = list(dict.fromkeys(str(p) for p in paths))
    for offset, path in enumerate(names):
        env[f"GIT_CONFIG_KEY_{base + offset}"] = "safe.directory"
        env[f"GIT_CONFIG_VALUE_{base + offset}"] = path
    env["GIT_CONFIG_COUNT"] = str(base + len(names))
    return env


def run(
    cmd: list[str],
    cwd: Path | None = None,
    *,
    check: bool = True,
    trust: tuple[str, ...] = (),
) -> subprocess.CompletedProcess[str]:
    env = (
        git_env(*(([str(cwd)] if cwd else []) + list(trust)))
        if cmd and cmd[0] == "git"
        else None
    )
    return subprocess.run(
        cmd, cwd=cwd, check=check, text=True, capture_output=True, env=env
    )


def die(msg: str) -> None:
    print(f"ERROR: {msg}", file=sys.stderr)
    raise SystemExit(1)


def check_fresh(repo: Path) -> None:
    """Warn when the branch being updated is behind the remote's default branch.

    Both update paths are 3-way merges and work fine from an outdated branch,
    but the PR back onto the default branch re-conflicts with everything that
    landed since the branch was cut. Warn only: unlike the one-time migration,
    ``copier update`` on a feature branch is a normal thing to do, so this must
    not block. The migration script enforces it for ``--yes``.

    Never fatal: a failed fetch (offline, no remote) just skips the check.
    """
    remotes = run(["git", "-C", str(repo), "remote"], check=False).stdout.split()
    if not remotes:
        return
    remote = "origin" if "origin" in remotes else remotes[0]

    def default_branch() -> str | None:
        out = run(
            [
                "git",
                "-C",
                str(repo),
                "symbolic-ref",
                "--quiet",
                "--short",
                f"refs/remotes/{remote}/HEAD",
            ],
            check=False,
        ).stdout.strip()
        name = out.removeprefix(f"{remote}/")
        if name:
            return name
        run(
            ["git", "-C", str(repo), "remote", "set-head", remote, "--auto"],
            check=False,
        )
        out = run(
            [
                "git",
                "-C",
                str(repo),
                "symbolic-ref",
                "--quiet",
                "--short",
                f"refs/remotes/{remote}/HEAD",
            ],
            check=False,
        ).stdout.strip()
        name = out.removeprefix(f"{remote}/")
        if name:
            return name
        for candidate in ("develop", "main", "master"):
            if (
                run(
                    [
                        "git",
                        "-C",
                        str(repo),
                        "rev-parse",
                        "--verify",
                        "--quiet",
                        f"refs/remotes/{remote}/{candidate}",
                    ],
                    check=False,
                ).returncode
                == 0
            ):
                return candidate
        return None

    branch = default_branch()
    if branch is None:
        return
    remote_ref = f"{remote}/{branch}"
    if (
        run(
            ["git", "-C", str(repo), "fetch", "--quiet", remote, branch], check=False
        ).returncode
        != 0
    ):
        return
    behind = run(
        ["git", "-C", str(repo), "rev-list", "--count", f"HEAD..{remote_ref}"],
        check=False,
    ).stdout.strip()
    if not behind.isdigit() or int(behind) == 0:
        return
    print(
        f"warning: HEAD is {behind} commit(s) behind {remote_ref}. The update works,\n"
        f"but the PR back onto {branch} will re-conflict with those commits; consider\n"
        f"rebasing onto {remote_ref} first.\n"
    )


def latest_copier_tag(clone: Path) -> str:
    """Newest tag that is a copier template (has copier.yaml/copier.yml)."""
    tags = run(
        [
            "git",
            "-C",
            str(clone),
            "for-each-ref",
            "--sort=-v:refname",
            "--format=%(refname:short)",
            "refs/tags",
        ],
        check=False,
        trust=(str(clone),),
    )
    names = [t for t in tags.stdout.split() if not t.endswith("^{}")]
    for tag in names:
        for marker in ("copier.yaml", "copier.yml"):
            probe = run(
                ["git", "-C", str(clone), "cat-file", "-e", f"{tag}:{marker}"],
                check=False,
                trust=(str(clone),),
            )
            if probe.returncode == 0:
                return tag
    return "HEAD"


def fetch_script(template: str, ref: str | None, workdir: Path) -> tuple[Path, str]:
    """Return (path to migrate_to_copier.py, resolved ref).

    Prefers the engine sitting next to this script (the normal case: run.sh
    clones the template at its newest copier tag and runs update.py from it, so
    the sibling engine is already the latest). Only when there is no sibling —
    update.py run standalone — does it clone the template to fetch the engine
    at the newest copier tag. A full clone is used (raptor is ~1 MB) because
    finding the newest copier tag needs every tag, and Azure DevOps serves
    neither ``git-upload-archive`` nor unauthenticated raw downloads, so a clone
    over the configured (ssh/https) credential is the only portable fetch.
    """
    sibling = Path(__file__).resolve().parent / SCRIPT_NAME
    if sibling.is_file():
        return sibling, ref or "(next to update.py)"

    clone = workdir / ".template"
    proc = run(
        ["git", "clone", "--quiet", "--no-local", template, str(clone)],
        check=False,
        trust=(str(clone),),
    )
    if proc.returncode != 0:
        die(
            f"could not clone the template {template}:\n{proc.stdout}{proc.stderr}"
            "Pass --template with a reachable URL or a local raptor path."
        )
    resolved = ref or latest_copier_tag(clone)
    checkout = run(["git", "checkout", "--quiet", resolved], clone, check=False)
    if checkout.returncode != 0:
        die(f"ref '{resolved}' not found in template {template}")
    script = clone / "scripts" / SCRIPT_NAME
    if not script.is_file():
        die(f"{template} @ {resolved} has no scripts/{SCRIPT_NAME}")
    return script, resolved


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--repo", default=".", type=Path, help="repo to update (default: cwd)"
    )
    parser.add_argument(
        "--template",
        default=DEFAULT_TEMPLATE,
        help=f"template URL/path (default: {DEFAULT_TEMPLATE})",
    )
    parser.add_argument(
        "--ref", default=None, help="template ref; default: newest copier tag"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="preview (copier repos: copier update --pretend)",
    )
    parser.add_argument(
        "--yes",
        action="store_true",
        help="apply (copier repos: copier update --defaults)",
    )
    parser.add_argument(
        "--allow-behind",
        action="store_true",
        help="proceed even when HEAD is behind the remote's default branch",
    )
    parser.add_argument(
        "-d", "--data", action="append", default=[], metavar="key=value"
    )
    parser.add_argument(
        "--keep-old-pipelines",
        action="store_true",
        help="migration of a package repo with the old azure-pipelines.yml: keep it (default: switch to ci/cd/release)",
    )
    args, extra = parser.parse_known_args()

    repo = args.repo.resolve()
    if (
        run(
            ["git", "-C", str(repo), "rev-parse", "--is-inside-work-tree"],
            check=False,
            trust=(str(repo),),
        ).returncode
        != 0
    ):
        die(f"{repo} is not a git repo")

    if (repo / ".copier-answers.yml").is_file():
        # copier-era repo: nothing to migrate, hand everything to copier
        if args.check and args.yes:
            die("pass either --check or --yes, not both")
        if not args.allow_behind:
            check_fresh(repo)
        # same flags as the migration, in copier's spelling, so run.sh and the
        # skill work unchanged on both routes:
        #   --ref -> --vcs-ref (run.sh always passes --ref, the ref it checked out)
        #   --check -> --pretend --defaults (preview, keep the recorded answers)
        #   --yes -> --defaults (apply non-interactively with the recorded answers)
        #   -d k=v -> --data k=v
        has_vcs_ref = any(a == "--vcs-ref" or a.startswith("--vcs-ref=") for a in extra)
        ref_args = ["--vcs-ref", args.ref] if args.ref and not has_vcs_ref else []
        mode_args = (
            ["--pretend", "--defaults"]
            if args.check
            else ["--defaults"]
            if args.yes
            else []
        )
        data_args = [arg for item in args.data for arg in ("--data", item)]
        cmd = ["copier", "update", "--trust", *ref_args, *mode_args, *data_args, *extra]
        print(f"copier repo: running {' '.join(cmd)}")
        return subprocess.run(cmd, cwd=repo, check=False, env=git_env(repo)).returncode

    # cookiecutter-era repo: one-time migration, fetched from the template itself
    print(
        "no .copier-answers.yml: cookiecutter-era repo, running the one-time migration"
    )
    if not (args.check or args.yes):
        die("refusing to write without --yes (use --check to preview)")
    if extra:
        die(f"unknown arguments for the migration: {' '.join(extra)}")
    if shutil.which("uv") is None:
        die(
            "uv is required to run the migration (curl -LsSf https://astral.sh/uv/install.sh | sh)"
        )
    with tempfile.TemporaryDirectory() as tmp:
        script, resolved = fetch_script(args.template, args.ref, Path(tmp))
        print(f"migration script: {SCRIPT_NAME} from {args.template} @ {resolved}")
        cmd = [
            "uv",
            "run",
            "--no-project",
            "--python",
            "3.11",
            str(script),
            "--repo",
            str(repo),
            "--template",
            args.template,
        ]
        for item in args.data:
            cmd += ["-d", item]
        if args.ref:
            cmd += ["--ref", args.ref]
        if args.allow_behind:
            cmd += ["--allow-behind"]
        if args.keep_old_pipelines:
            cmd += ["--keep-old-pipelines"]
        cmd += ["--yes"] if args.yes else ["--check"]
        return subprocess.run(cmd, check=False).returncode


if __name__ == "__main__":
    raise SystemExit(main())
